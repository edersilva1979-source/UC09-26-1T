    private void btnConcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConcluirActionPerformed
        int linha = tblServicos.getSelectedRow();
        
        if (linha ==-1 ){
            JOptionPane.showMessageDialog(this, "Selecione um servço para concluir");
            return;
        }
        
        int idServico = Integer.parseInt(tblServicos.getValueAt(linha,0).toString());
        
        if (Boolean.TRUE.equals(tblServicos.getValueAt(linha, 7))){
            JOptionPane.showMessageDialog(this,"Este serviço já esta Concluido");
            return;
        }
        
        int resposta = JOptionPane.showConfirmDialog(this,
                                   "Confirma a conclusão do serviço nº: " + idServico + "?",
                                   "Concluir Serviço",
                                   JOptionPane.YES_NO_OPTION);
        
        if (resposta != JOptionPane.YES_OPTION) return;
        
        String sql = """
                     UPDATE servico_zoo
                     SET executado = TRUE 
                     WHERE id = ? AND executado = FALSE
                     """;
        
        try (Connection conex = Conexao.conectar();
               PreparedStatement stmt = conex.prepareStatement(sql) ){
            stmt.setInt(1,idServico);
            int linhas = stmt.executeUpdate();
            
            JOptionPane.showMessageDialog(this,
                        linhas == 1 ? "Serviço Concluido com sucesso!"
                                : "Serviço não encontrado ou já concluído");
            atualizarTabela();
            limparCampos();
        } catch (SQLException erro){
                 JOptionPane.showMessageDialog(this, "Erro ao concluir seriço: "+erro.getMessage());
        }
        
    }//GEN-LAST:event_btnConcluirActionPerformed

